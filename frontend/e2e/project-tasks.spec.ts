import {test,expect} from '@playwright/test';
const KEY='personalmanagement:pages-demo:v1';
const storage=page=>page.evaluate(k=>JSON.parse(localStorage.getItem(k)||'{}'),KEY);
test('task without time saves in list but never in calendar',async({page})=>{
 await page.goto('/');
 await page.locator('.nav-item',{hasText:'Все задачи'}).click();
 await page.getByRole('button',{name:'Добавить задачу',exact:true}).click();
 await page.locator('.drawer input').first().fill('Без времени');
 await expect(page.locator('.drawer button[type="submit"]')).toBeEnabled();
 await page.locator('.drawer button[type="submit"]').click();
 await expect(page.locator('.task-priority-matrix')).toContainText('Без времени');
 expect((await storage(page)).tasks.find(t=>t.title==='Без времени')?.scheduled_at).toBeNull();
 await page.locator('.nav-item',{hasText:'Календарь'}).click();
 await expect(page.locator('.cal-item',{hasText:'Без времени'})).toHaveCount(0);
 await expect(page.locator('.backlog-task',{hasText:'Без времени'})).toHaveCount(1);
});
test('calendar requires a scheduled time',async({page})=>{
 await page.goto('/');
 await page.locator('.top-actions .primary-btn').click();
 const drawer=page.locator('.drawer');
 await drawer.locator('input').first().fill('Новая календарная');
 await expect(drawer.locator('button[type="submit"]')).toBeDisabled();
 await expect(drawer.locator('input[type="datetime-local"]').first()).toHaveAttribute('aria-invalid','true');
 await drawer.locator('button.cancel-task-btn').click();
 await expect(drawer).toHaveCount(0);
});
test('priority matrix and completed tasks each collapse independently',async({page})=>{
 await page.goto('/');
 await page.evaluate(key=>{
  const data=JSON.parse(localStorage.getItem(key)),base=data.tasks[0];
  data.tasks.push({...base,id:5001,title:'Срочное P3',priority:3,status:'planned',scheduled_at:null,recurrence:''});
  data.tasks.push({...base,id:5002,title:'Завершено',status:'done',scheduled_at:null,recurrence:''});
  localStorage.setItem(key,JSON.stringify(data));
 },KEY);
 await page.reload();
 await page.locator('.nav-item',{hasText:'Все задачи'}).click();
 const p3=page.locator('details.m3');
 await expect(p3).not.toHaveAttribute('open','');
 await p3.locator(':scope > summary').click();
 await expect(p3).toHaveAttribute('open','');
 await expect(p3).toContainText('Срочное P3');
 const completed=page.locator('details.completed-group').first();
 await expect(completed).not.toHaveAttribute('open','');
 await completed.locator(':scope > summary').click();
 await expect(completed).toContainText('Завершено');
});
test('project opens its container; multi-direction edit is separate',async({page})=>{
 await page.goto('/');
 await page.locator('.nav-item',{hasText:'Проекты'}).click();
 await page.getByRole('button',{name:'Проект',exact:true}).click();
 await page.locator('.drawer input').first().fill('Много направлений');
 await page.locator('.project-areas-picker input').nth(0).check();
 await page.locator('.project-areas-picker input').nth(1).check();
 await page.locator('.drawer button[type="submit"]').click();
 await page.getByRole('button',{name:'Открыть проект Много направлений'}).click();
 const container=page.locator('.project-workspace');
 await expect(container).toContainText('Много направлений');
 await expect(page.locator('.drawer')).toHaveCount(0);
 await expect(container.locator('.project-area-tag')).toHaveCount(2);
 await expect(container.getByRole('heading',{name:'События',exact:true})).toHaveCount(0);
 await container.getByRole('button',{name:'Редактировать проект'}).click();
 await expect(page.locator('.drawer')).toBeVisible();
 await page.locator('.project-areas-picker input').nth(0).uncheck();
 await page.locator('.drawer button[type="submit"]').click();
 await expect(container.locator('.project-area-tag')).toHaveCount(1);
 await container.getByRole('button',{name:'Задача',exact:true}).click();
 await page.locator('.drawer input').first().fill('Задача проекта без времени');
 await expect(page.locator('.drawer button[type="submit"]')).toBeEnabled();
 await page.locator('.drawer button[type="submit"]').click();
 await expect(container).toContainText('Задача проекта без времени');
 const state=await storage(page);
 const project=state.projects.find(p=>p.title==='Много направлений');
 const task=state.tasks.find(t=>t.title==='Задача проекта без времени');
 expect(project.area_ids).toHaveLength(1);
 expect(task.project_id).toBe(project.id);
 expect(task.scheduled_at).toBeNull();
});

